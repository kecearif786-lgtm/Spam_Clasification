-- Shared history for the public Streamlit Spam Detector AI application.
-- Run this script once in Supabase Dashboard -> SQL Editor.

create table if not exists public.spam_analysis_history (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    source text not null check (source in ('Input teks', 'Screenshot OCR')),
    label text not null check (label in ('SPAM', 'HAM')),
    confidence double precision null
        check (confidence is null or (confidence >= 0 and confidence <= 100)),
    message_text text not null
        check (char_length(message_text) between 1 and 20000)
);

create index if not exists spam_analysis_history_created_at_idx
    on public.spam_analysis_history (created_at desc);

create index if not exists spam_analysis_history_label_idx
    on public.spam_analysis_history (label);

-- Enable RLS and do not grant public/anonymous access.
-- The Streamlit server uses a Supabase Secret key stored in Streamlit Secrets.
alter table public.spam_analysis_history enable row level security;

revoke all privileges on table public.spam_analysis_history from public, anon, authenticated;
grant select, insert, delete on table public.spam_analysis_history to service_role;

revoke all privileges on sequence public.spam_analysis_history_id_seq from public, anon, authenticated;
grant usage, select on sequence public.spam_analysis_history_id_seq to service_role;
